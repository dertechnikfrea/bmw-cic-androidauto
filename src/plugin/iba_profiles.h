/* HmiMain build profiles.
 *
 * Every HmiMain address in AAPlugin.cpp, iba_firmware.h and iba_marshal.h is written
 * for the build the plugin was developed on (E9x, HmiMain 9283417A, SHA256 dbeef804...).
 * Other builds of the same CIC software contain the same code moved by a few KB.
 * A profile translates each of those addresses for one build; addresses that are not
 * in its table are used unchanged. Fingerprints whose literal pool words move with the
 * code get the bytes of that build in its SigFix table.
 *
 * The profile is chosen at run time: the first one whose 47 fingerprints (anchors +
 * marshal) all match the running HmiMain. If none matches nothing is called, exactly
 * as before. To add a build, run tools/hmi_profile.py on its HmiMain and paste the
 * output here (see the README). */
struct IbaXlat { unsigned long from, to; };
struct IbaSigFix { unsigned long from; unsigned char bytes[32]; };
struct IbaProfile {
    const char* name;
    const IbaXlat* xlat; unsigned nxlat;
    const IbaSigFix* fix; unsigned nfix;
};

