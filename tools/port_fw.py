"""Generate src/plugin/iba_fw_ports.h: C1A anchor tables rebased onto other HmiMain builds.

Usage: python -I tools/port_fw.py <HmiMain Rev76617> <HmiMain Rev58135> > src/plugin/iba_fw_ports.h

Every function/vtable the plugin uses in the C1A HmiMain (SHA256 dbeef804...) was
matched against each build: function bodies are byte-identical, only shifted by
region. The region maps below must stay in sync with kFwMap* in AAPlugin.cpp.
"""
import hashlib, re, sys, os
B = 0x08040000
# (lo, hi, delta) on C1A addresses; first match wins
MAPS = {
    '76617': [(0x09000000, 0x0a000000, 0x7dc), (0x08ad0000, 0x09000000, 0x408),
              (0x08930000, 0x08940000, 0x3fc), (0x082b0000, 0x082d0000, 0xbc),
              (0x08040000, 0x08210000, 0xa0)],
    '58135': [(0x09000000, 0x0a000000, -0x116c), (0x08ce4000, 0x09000000, -0xfe4),
              (0x08ce0000, 0x08ce4000, -0xeac), (0x08ad0000, 0x08ce0000, -0xe90),
              (0x08930000, 0x08940000, -0xda0), (0x082b0000, 0x082d0000, -0x138),
              (0x08040000, 0x08210000, -0x120)],
}
def hm(fw, a):
    for lo, hi, d in MAPS[fw]:
        if lo <= a < hi: return a + d
    raise SystemExit('unmapped %x for %s' % (a, fw))
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'plugin')
print('/* Generated by tools/port_fw.py; do not hand-edit. */')
for fw, path in zip(('76617', '58135'), sys.argv[1:3]):
    N = open(path, 'rb').read()
    print('/* HmiMain Rev %s SHA256 %s */' % (fw, hashlib.sha256(N).hexdigest()))
    for hdr, name, typ in (('iba_firmware.h', 'kIbaAnchors', 'IbaAnchor'),
                           ('iba_marshal.h', 'kIbaMarshalSigs', 'IbaMarshalSig')):
        src = open(os.path.join(here, hdr)).read().split('[]', 1)[1]
        print('static const %s %s%s[]={' % (typ, name, fw))
        for m in re.finditer(r'\{0x([0-9a-f]+)UL,', src):
            a = hm(fw, int(m.group(1), 16)); o = a - B
            print('{0x%xUL,{%s}},' % (a, ','.join('0x%02x' % c for c in N[o:o + 32])))
        print('};')
