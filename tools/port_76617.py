"""Generate src/plugin/iba_fw76617.h: C1A anchor tables rebased onto HmiMain Rev 76617.

Usage: python -I tools/port_76617.py <HmiMain Rev76617> > src/plugin/iba_fw76617.h
The shift map below was derived by matching every function body/vtable of the C1A
HmiMain (SHA256 dbeef804...) against Rev 76617 (MD5 86778b2f...); keep it in sync
with hm_76617() in AAPlugin.cpp.
"""
import hashlib, re, sys, os
B = 0x08040000
def hm(a):
    if a >= 0x09000000: return a + 0x7dc
    if a >= 0x08ad0000: return a + 0x408
    if 0x08930000 <= a < 0x08940000: return a + 0x3fc
    if 0x082b0000 <= a < 0x082d0000: return a + 0xbc
    if a < 0x08210000: return a + 0xa0
    raise SystemExit('unmapped %x' % a)
N = open(sys.argv[1], 'rb').read()
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'plugin')
print('/* Generated by tools/port_76617.py from HmiMain Rev 76617 SHA256 %s; do not hand-edit. */'
      % hashlib.sha256(N).hexdigest())
for hdr, name, typ in (('iba_firmware.h', 'kIbaAnchors76617', 'IbaAnchor'),
                       ('iba_marshal.h', 'kIbaMarshalSigs76617', 'IbaMarshalSig')):
    src = open(os.path.join(here, hdr)).read().split('[]', 1)[1]
    print('static const %s %s[]={' % (typ, name))
    for m in re.finditer(r'\{0x([0-9a-f]+)UL,', src):
        a = hm(int(m.group(1), 16)); o = a - B
        print('{0x%xUL,{%s}},' % (a, ','.join('0x%02x' % c for c in N[o:o + 32])))
    print('};')
